"use client";

import { useEffect, useRef, useState } from "react";
import Image from "next/image";
import { usePathname } from "next/navigation";
import type { Locale } from "@/lib/i18n";
import { readCart } from "@/lib/hardwareCart";
import { readStoreView, subscribeStoreView, type StoreView } from "@/lib/storeView";
import AssistantMessageBody from "@/components/AssistantMessageBody";
import BaamixThinking, { HamsterWheel } from "@/components/BaamixThinking";
import { IS_ONION, CLEARNET_URL } from "@/lib/onion";
import "@/styles/split/pages-misc.css";



/**
 * Miroir Tor : Baamix ne peut pas répondre (aucun serveur, et les services d'IA tiers feraient sortir
 * les messages du réseau Tor). Le chat s'ouvre donc sur un message déjà "envoyé" par Baamix, qui
 * explique pourquoi. Aucun appel réseau n'est fait dans ce mode.
 */
function onionIntro(locale: Locale): string {
  if (locale === "en") {
    return `Hello, this is Baamix. I would rather be honest right away: on the Tor mirror, I cannot chat with you.

Here is why:

- **I do not run here.** This version of the site is a simple set of files, with no server. To answer, I need a third-party artificial intelligence service.
- **Your messages would leave Tor.** If I forwarded them to that service, they would exit the Tor network to be processed elsewhere, and the anonymity you came here for would be gone. I would rather stay silent than betray you.
- **I do not want to follow you.** This mirror contacts no outside service and keeps no visit log. I respect that rule.

What you can do:

- Read the [documentation](/${locale}/documentation) and the [FAQ](/${locale}/documentation/faq): they hold the same answers I would give.
- Find me on [bobine.fit](${CLEARNET_URL}/${locale}/baamix), outside Tor. My answers are then generated by third-party services (see the privacy policy).

See you soon, and thank you for supporting Tor and free software.`;
  }
  return `Bonjour, c'est Baamix. Je préfère être honnête tout de suite : sur le miroir Tor, je ne peux pas discuter avec vous.

Voici pourquoi :

- **Je ne tourne pas ici.** Cette version du site est un simple ensemble de fichiers, sans serveur. Pour répondre, j'ai besoin d'un service d'intelligence artificielle tiers.
- **Vos messages quitteraient Tor.** Si je les transmettais à ce service, ils sortiraient du réseau Tor pour être traités ailleurs, et l'anonymat que vous êtes venu chercher ici n'aurait plus aucun sens. Je préfère me taire plutôt que vous trahir.
- **Je ne veux pas vous suivre.** Ce miroir ne contacte aucun service extérieur et ne garde aucun journal de visite. Je respecte cette règle.

Ce que vous pouvez faire :

- Lire la [documentation](/${locale}/documentation) et la [FAQ](/${locale}/documentation/faq) : elles contiennent les mêmes réponses que moi.
- Me retrouver sur [bobine.fit](${CLEARNET_URL}/${locale}/baamix), hors de Tor. Mes réponses sont alors générées par des services tiers (voir la politique de confidentialité).

À bientôt, et merci de soutenir Tor et le logiciel libre.`;
}

interface Message {
  role: "user" | "assistant";
  content: string;
}

/**
 * Le même assistant sous deux formes : la bulle flottante (variant "bubble", montée dans toutes les
 * pages) et la page plein écran /baamix (variant "page", toujours ouverte, sans fermeture).
 */
export default function BobineChatbot({ locale, variant = "bubble" }: { locale: Locale; variant?: "bubble" | "page" }) {
  const isEn = locale === "en";
  const isPage = variant === "page";
  const pathname = usePathname();
  // Sur la page /baamix, la bulle disparaît : une seule conversation à l'écran.
  const hiddenBubble = !isPage && Boolean(pathname?.includes("/baamix"));
  const [isOpen, setIsOpen] = useState(isPage);
  const [messages, setMessages] = useState<Message[]>(
    IS_ONION ? [{ role: "assistant", content: onionIntro(locale) }] : [],
  );
  const [input, setInput] = useState("");
  // Miroir Tor : une fois le message de Baamix entièrement tapé, il court dans sa roue en bas du chat.
  const [onionTyped, setOnionTyped] = useState(false);
  // Miroir Tor : la frappe repart de zéro à chaque ouverture du chat (le contenu reste monté, masqué, dès l'arrivée).
  const [openNonce, setOpenNonce] = useState(0);
  const [isLoading, setIsLoading] = useState(false);
  const modalRef = useRef<HTMLDivElement>(null);
  const messagesEndRef = useRef<HTMLDivElement>(null);
  const bodyRef = useRef<HTMLDivElement>(null);
  const inputRef = useRef<HTMLInputElement>(null);

  // Miroir Tor : précharge le rendu Markdown dès le chargement de la page (réseau lent), pour que la machine à
  // écrire démarre dès l'ouverture du chat.
  useEffect(() => {
    if (IS_ONION) void import("./MarkdownRenderer");
  }, []);

  // Ce que le visiteur regarde dans la boutique (publié par /materiel) : sert à proposer des questions adaptées.
  const [storeView, setStoreView] = useState<StoreView | null>(null);
  useEffect(() => {
    setStoreView(readStoreView());
    return subscribeStoreView(() => setStoreView(readStoreView()));
  }, []);

  const baseSuggestions = isEn
    ? [
        "What hardware should I buy for my gym?",
        "Amazon or AliExpress: which one should I choose?",
        "Mini PC or laptop for a control room?",
        "How is Bobine free with no subscription?",
        "How do I install Bobine on Debian?",
        "How does the one-click backup and restore work?",
      ]
    : [
        "Quel matériel acheter pour ma salle ?",
        "Amazon ou AliExpress : que choisir ?",
        "Mini PC ou PC portable pour une régie ?",
        "Pourquoi Bobine est gratuit sans abonnement ?",
        "Comment installer Bobine sur Debian ?",
        "Comment fonctionne la sauvegarde en un clic ?",
      ];

  // Sur la boutique, les questions portent sur ce qui est affiché ; sinon les questions de base.
  const storeSuggestions = isEn
    ? [
        "Compare the products shown here",
        "Which one is best for a quiet 24/7 room?",
        "Is the cheaper option worth it?",
        "What am I missing to complete this setup?",
      ]
    : [
        "Compare les produits affichés ici",
        "Lequel choisir pour une salle silencieuse 24 h sur 24 ?",
        "L'option la moins chère est-elle suffisante ?",
        "Que me manque-t-il pour compléter ce pack ?",
      ];

  const suggestions = storeView ? [...storeSuggestions, baseSuggestions[1], baseSuggestions[0]] : baseSuggestions;

  const defaultGreeting = isEn
    ? "Hello! I am Baamix, the Bobine mascot. Have a question about Bobine or equipping your gym? I recommend and compare hardware from both Amazon and AliExpress."
    : "Bonjour, je suis Baamix la mascotte de Bobine ! Une question sur Bobine ou l'équipement de votre salle ? Je recommande et compare le matériel d'Amazon comme d'AliExpress.";

  useEffect(() => {
    function handleToggle() {
      setIsOpen((prev) => !prev);
    }
    function handleOpen() {
      setIsOpen(true);
    }
    function handleClose() {
      setIsOpen(false);
    }

    if (isPage) return;
    window.addEventListener("toggle-baamix", handleToggle);
    window.addEventListener("open-baamix", handleOpen);
    window.addEventListener("close-baamix", handleClose);

    return () => {
      window.removeEventListener("toggle-baamix", handleToggle);
      window.removeEventListener("open-baamix", handleOpen);
      window.removeEventListener("close-baamix", handleClose);
    };
  }, []);

  // Défilement interne au chat (jamais de scrollIntoView : il ferait défiler toute la page /baamix).
  useEffect(() => {
    const body = bodyRef.current;
    if (body && messages.length > 0) {
      body.scrollTo({ top: body.scrollHeight, behavior: "smooth" });
    }
  }, [messages, isLoading]);

  useEffect(() => {
    if (isPage) {
      if (inputRef.current) inputRef.current.focus({ preventScroll: true });
      return;
    }
    if (isOpen) {
      document.body.style.overflow = "hidden";
      if (inputRef.current) {
        inputRef.current.focus();
      }
    } else {
      document.body.style.overflow = "";
    }
    return () => {
      document.body.style.overflow = "";
    };
  }, [isOpen]);

  useEffect(() => {
    if (IS_ONION && !isPage && isOpen && !hiddenBubble) {
      setOpenNonce((n) => n + 1);
      setOnionTyped(false);
    }
  }, [isOpen, hiddenBubble, isPage]);

  // Fermeture par clic extérieur et touche Échap
  useEffect(() => {
    function handleKeyDown(e: KeyboardEvent) {
      if (e.key === "Escape" && isOpen) {
        setIsOpen(false);
      }
    }

    function handleClickOutside(e: MouseEvent) {
      if (
        isOpen &&
        modalRef.current &&
        !modalRef.current.contains(e.target as Node) &&
        !(e.target as HTMLElement).closest(".baamix-header-btn") &&
        !(e.target as HTMLElement).closest(".mobile-drawer-baamix-btn")
      ) {
        setIsOpen(false);
      }
    }

    if (isOpen && !isPage) {
      window.addEventListener("keydown", handleKeyDown);
      document.addEventListener("mousedown", handleClickOutside);
    }

    return () => {
      window.removeEventListener("keydown", handleKeyDown);
      document.removeEventListener("mousedown", handleClickOutside);
    };
  }, [isOpen]);

  // Suit la frappe : reste collé en bas tant que le lecteur n'a pas remonté la conversation.
  function keepBottomVisible() {
    const body = bodyRef.current;
    if (body && body.scrollHeight - body.scrollTop - body.clientHeight < 160) {
      body.scrollTop = body.scrollHeight;
    }
  }

  async function sendMessage(textToSend?: string) {
    const messageContent = (textToSend || input).trim();
    if (IS_ONION || !messageContent || isLoading) return;

    const userMessage: Message = { role: "user", content: messageContent };
    const assistantMessage: Message = { role: "assistant", content: "" };

    setMessages((prev) => [...prev, userMessage, assistantMessage]);
    setInput("");
    setIsLoading(true);

    try {
      const response = await fetch("/api/chat", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          messages: [...messages, userMessage],
          locale,
          cart: readCart(),
          storeView: readStoreView(),
        }),
      });

      if (!response.ok) {
        const errData = await response.json().catch(() => ({}));
        throw new Error(errData.error || (isEn ? "Server communication error." : "Erreur de communication avec le serveur."));
      }

      if (!response.body) {
        throw new Error(isEn ? "Response stream unavailable." : "Flux de réponse indisponible.");
      }

      const reader = response.body.getReader();
      const decoder = new TextDecoder();
      let accumulated = "";

      while (true) {
        const { done, value } = await reader.read();
        if (done) break;

        const chunk = decoder.decode(value, { stream: true });
        accumulated = `${accumulated}${chunk}`;
        const currentText = accumulated;

        setMessages((prev) => {
          const list = prev.slice(0, -1);
          return [...list, { role: "assistant", content: currentText }];
        });
      }
    } catch (err: unknown) {
      const errorMsg =
        err instanceof Error ? err.message : (isEn ? "Message generation error." : "Erreur de génération du message.");
      setMessages((prev) => {
        const list = prev.slice(0, -1);
        return [
          ...list,
          {
            role: "assistant",
            content: isEn ? `Error: ${errorMsg}` : `Erreur : ${errorMsg}`,
          },
        ];
      });
    } finally {
      setIsLoading(false);
    }
  }

  function handleKeyDownInput(e: React.KeyboardEvent<HTMLInputElement>) {
    if (e.key === "Enter" && !e.shiftKey) {
      e.preventDefault();
      sendMessage();
    }
  }

  const hidden = !isOpen || hiddenBubble;
  // Miroir Tor : le chat est monté dès l'arrivée sur le site, simplement masqué. Le rendu Markdown se charge
  // en arrière-plan et le message est prêt : à l'ouverture, seule l'animation de frappe se joue (plus de demi-bulle).
  if (hidden && !IS_ONION) {
    return null;
  }

  return (
    <div
      ref={modalRef}
      className={`chatbot-modal${isPage ? " chatbot-modal--page" : ""}`}
      aria-hidden={hidden || undefined}
      role={isPage ? "region" : "dialog"}
      aria-modal={isPage ? undefined : true}
      aria-label={isPage ? (isEn ? "Baamix AI assistant" : "Assistant IA Baamix") : undefined}
    >
      {/* Page /baamix : titre principal accessible mais invisible (le chat occupe tout l'écran, sans en-tête). */}
      {isPage && <h1 className="sr-only">{isEn ? "Baamix, the Bobine AI assistant" : "Baamix, l'assistant IA de Bobine"}</h1>}

      {/* En-tête (bulle uniquement) */}
      {!isPage && (
      <div className="chatbot-modal__header">
        <div className="chatbot-modal__title-group">
          <div className="chatbot-avatar">
            <Image
              src="/images/baamix-cutout.webp"
              alt="Baamix"
              width={34}
              height={34}
              className="chatbot-avatar-img"
            />
            <span className="chatbot-avatar-status" />
          </div>
          <div>
            <span className="chatbot-modal__title bobine-chatbot-span-1">Baamix</span>
            <span className="chatbot-modal__subtitle">{isEn ? "Bobine Mascot & Fanta's Daughter" : "Mascotte de Bobine & Fille de Fanta"}</span>
          </div>
        </div>
            <div className="bobine-chatbot-div-1">
              {messages.length > 0 && (
                <button
                  type="button"
                  className="chatbot-header-btn"
                  onClick={() => setMessages([])}
                  title={isEn ? "Reset chat" : "Réinitialiser la conversation"}
                  aria-label={isEn ? "Reset chat" : "Réinitialiser"}
                >
                  <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
                    <polyline points="1 4 1 10 7 10" />
                    <path d="M3.51 15a9 9 0 1 0 2.13-9.36L1 10" />
                  </svg>
                </button>
              )}
              {!isPage && (
              <button
                type="button"
                className="chatbot-header-btn"
                onClick={() => setIsOpen(false)}
                aria-label={isEn ? "Close" : "Fermer"}
                title={isEn ? "Close assistant" : "Fermer l'assistant"}
              >
                <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.5" strokeLinecap="round" strokeLinejoin="round">
                  <line x1="18" y1="6" x2="6" y2="18" />
                  <line x1="6" y1="6" x2="18" y2="18" />
                </svg>
              </button>
              )}
            </div>
          </div>
      )}

      {/* Page /baamix : bouton discret de nouvelle conversation */}
      {isPage && !IS_ONION && messages.length > 0 && (
        <button type="button" className="chatbot-page-reset" onClick={() => setMessages([])}>
          <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
            <path d="M12 5v14M5 12h14" />
          </svg>
          {isEn ? "New conversation" : "Nouvelle conversation"}
        </button>
      )}

          {/* Corps de conversation */}
          <div ref={bodyRef} className={`chatbot-modal__body${messages.length === 0 ? " chatbot-modal__body--empty" : ""}`}>
            {!IS_ONION && (
            <>{/* Message de bienvenue */}
            <div className="chatbot-message chatbot-message--assistant">
              <div className="chatbot-message__avatar">
                <Image
                  src="/images/baamix-cutout.webp"
                  alt="Baamix"
                  width={26}
                  height={26}
                  className="chatbot-avatar-img"
                />
              </div>
              <div className="chatbot-message__bubble">
                <p className="bobine-chatbot-p-1">{defaultGreeting}</p>
              </div>
            </div></>
            )}

            {/* Suggestions initiales */}
            {messages.length === 0 && (
              <div className="chatbot-suggestions">
                <span className="chatbot-suggestions__title">
                  {isEn ? "Suggested questions:" : "Questions fréquentes :"}
                </span>
                <div className="chatbot-suggestions__list">
                  {suggestions.map((sug, idx) => (
                    <button
                      key={idx}
                      type="button"
                      className="chatbot-suggestion-chip"
                      onClick={() => sendMessage(sug)}
                    >
                      {sug}
                    </button>
                  ))}
                </div>
              </div>
            )}

            {/* Messages échangés */}
            {messages.map((m, idx) => {
              if (m.role === "assistant" && !m.content) {
                return (
                  <div key={idx} className="chatbot-message chatbot-message--assistant">
                    <div className="chatbot-message__avatar">
                      <Image
                        src="/images/baamix-cutout.webp"
                        alt="Baamix"
                        width={26}
                        height={26}
                        className="chatbot-avatar-img"
                      />
                    </div>
                    <div className="chatbot-message__bubble chatbot-message__typing">
                      <BaamixThinking isEn={isEn} hasStoreContext={storeView !== null} />
                    </div>
                  </div>
                );
              }

              return (
                <div
                  key={idx}
                  className={`chatbot-message chatbot-message--${m.role}`}
                >
                  {m.role === "assistant" && (
                    <div className="chatbot-message__avatar">
                      <Image
                        src="/images/baamix-cutout.webp"
                        alt="Baamix"
                        width={26}
                        height={26}
                        className="chatbot-avatar-img"
                      />
                    </div>
                  )}
                  <div className="chatbot-message__bubble">
                    {m.role === "assistant" ? (
                      <AssistantMessageBody
                        raw={m.content}
                        streaming={isLoading && idx === messages.length - 1}
                        animate={idx === messages.length - 1}
                        locale={locale}
                        onGrow={keepBottomVisible}
                        onDone={IS_ONION ? () => setOnionTyped(true) : undefined}
                        active={!hidden}
                        key={`${idx}-${openNonce}`}
                      />
                    ) : (
                      <p className="bobine-chatbot-p-1">{m.content}</p>
                    )}
                  </div>
                </div>
              );
            })}

            {IS_ONION && onionTyped && (
              <div className="baamix-idle-runner" role="img" aria-label={isEn ? "Baamix running in its wheel" : "Baamix court dans sa roue"}>
                <HamsterWheel />
                <span className="baamix-idle-runner__text">
                  {isEn ? "Baamix keeps running while you read the documentation." : "Baamix court dans sa roue pendant que vous lisez la documentation."}
                </span>
              </div>
            )}

            <div ref={messagesEndRef} />
          </div>

          {/* Formulaire d'envoi */}
          <div className="chatbot-modal__footer">
            <div className="chatbot-input-wrapper">
              <input
                ref={inputRef}
                type="text"
                className="chatbot-input"
                placeholder={
                  IS_ONION
                    ? isEn
                      ? "Baamix is resting on the Tor mirror (see his message above)"
                      : "Baamix est en veille sur le miroir Tor (voir son message ci-dessus)"
                    : isEn
                    ? "Ask Baamix (Amazon and AliExpress hardware, setup)..."
                    : "Posez votre question à Baamix (matériel Amazon et AliExpress, installation)..."
                }
                value={input}
                onChange={(e) => setInput(e.target.value)}
                onKeyDown={handleKeyDownInput}
                disabled={isLoading || IS_ONION}
              />
              <button
                type="button"
                className="chatbot-send-btn"
                onClick={() => sendMessage()}
                disabled={IS_ONION || !input.trim() || isLoading}
                aria-label={isEn ? "Send" : "Envoyer"}
              >
                <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.5" strokeLinecap="round" strokeLinejoin="round">
                  <line x1="22" y1="2" x2="11" y2="13" />
                  <polygon points="22 2 15 22 11 13 2 9 22 2" />
                </svg>
              </button>
            </div>
            <div className="chatbot-badge-disclaimer">
              {isEn
                ? "Baamix Commerciale · Sovereign AGPL-3.0"
                : "Baamix Commerciale · Logiciel Libre AGPL-3.0"}
            </div>
          </div>
        </div>
  );
}
